"""机器替黄维说出口的那两句自相矛盾的话——2026-10-08 定的口径、11-04 线上还在发。

两条都有盘上实证，不是推测：

① 「我主要找线上数据分析这类的」——这句**写在默认系统提示词里**。
   他 10-08 晚为这件事改过两次口径（`reply_engine.FAMILY_DECLINE_REPLY` 上面那段注释
   就是那次留下的）：「不要再说什么只招线上兼职这种话，你就说不要给我推荐这类岗位就行了」。
   可提示词这一头一直留着那句反着写的指令，11-04 14:51:26 童女士那一路线上真的发了出来。
   简历此刻写的是长沙·全职——机器替他喊"线上"，一是跟简历打架，二是给 HR 递话
   （"我们也线上的呀""居家主播就是线上"），这一类岗位本来就说过不要推荐。

② 「之前聊的**兼职·**视觉理解数据标注与质量评测我很有兴趣」——11-04 11:59:54 杨女士那一路。
   `洗岗位标题` 以前只切**尾巴**那串「查看职位」，标题**开头**的「兼职·」是 BOSS 拼的
   前缀（盘上 2505 个会话 48% 带它），原样念出去就成了替他自报"兼职"，
   还把 11-01 起就不投了的数据标注方向又报了一遍。

两头各配反向哨兵：判据拆掉要红，判据写过头（把没前缀的岗位名也切了）也要红。
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
sys.path.insert(0, str(ROOT))

from boss_bot.contact_ledger import 洗岗位标题  # noqa: E402
from boss_bot.prompts import build_system_prompt  # noqa: E402

# 他本人定过的、机器不许再自报的那几种说法
自报口径 = ["我主要找线上", "我只找线上", "只招线上", "可以线上远程", "接受兼职"]


class Test默认提示词不再教机器自报线上:
    def _默认(self):
        return build_system_prompt({
            "name": "黄维", "education": "本科在读（长沙理工大学 · 风景园林，2023-2027），双一流",
            "experience": "做过 AIGC 产品从 0 到 1", "position": "AI产品经理（长沙 · 全职）"})

    def test_那句教他说线上的话没了(self):
        文 = self._默认()
        for 说 in 自报口径:
            assert 说 not in 文, "提示词里还在教机器自报「%s」——他 10-08 就禁过这种说法" % 说

    def test_关上门不解释这条写进去了(self):
        """方向不对的那一路要的是关门，不是报方向：换成别的说法也得留住这条意思。"""
        文 = self._默认()
        assert "这类岗位我不考虑" in 文 or "不用再给我推荐" in 文
        assert "长沙·全职" in 文 or "长沙 · 全职" in 文, \
            "提示词没说清简历上是长沙全职，模型下次还会自己补一句线上"

    def test_画像那一行照样进提示词(self):
        """关门这条不许是把整段规则删短换来的——画像/求职意向照旧要喂进去。"""
        文 = self._默认()
        assert "AI产品经理（长沙 · 全职）" in 文
        assert "双一流" in 文


class Test标题开头那个前缀不再念给对方:
    def test_兼职前缀切掉(self):
        assert 洗岗位标题("兼职·视觉理解数据标注与质量评测") == "视觉理解数据标注与质量评测"
        assert 洗岗位标题("兼职·数据标注/AI训练师80-100元/天") == "数据标注/AI训练师80-100元/天"

    def test_实习校招前缀也切(self):
        for 头 in ("实习·", "全职·", "校招·", "社招·"):
            assert 洗岗位标题(头 + "算法产品经理") == "算法产品经理", 头

    def test_尾巴那串照旧切(self):
        """反向哨兵：加了切头这一刀，别把以前修好的切尾丢掉（那句 2778 个会话的实证）。"""
        assert 洗岗位标题("人力招聘实习生100-150元/天长沙查看职位") == \
            "人力招聘实习生100-150元/天长沙"
        assert "查看职位" not in 洗岗位标题("数据分析专员查看职位详情")

    def test_岗位名自己带兼职两个字不许被切(self):
        """「兼职助教」是一个岗位，不是前缀：判据过头会把岗位名切成"助教"。"""
        assert 洗岗位标题("兼职助教（周末）") == "兼职助教（周末）"
        assert 洗岗位标题("数据分析师") == "数据分析师"

    def test_空值和怪形状不炸(self):
        for 怪 in (None, "", "   ", "兼职·", "·"):
            assert isinstance(洗岗位标题(怪), str)

    def test_跟进句那条路真的用了这一句判据(self):
        """界面/台账/跟进句三处读标题都得走 `洗岗位标题`，抄第二套就有漏网的。"""
        源 = (ROOT / "boss_bot" / "main_loop.py").read_text(encoding="utf-8")
        段 = 源[源.index("from boss_bot.contact_ledger import split_job_title, 洗岗位标题") - 1500:
               源.index("from boss_bot.contact_ledger import split_job_title, 洗岗位标题") + 1500]
        assert "洗岗位标题(" in 段, "跟进句不再过洗标题那一句了"
