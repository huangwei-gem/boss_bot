"""标题已经是数据/分析这一类时，正文里的"销售"是被分析的业务域，不是这份工本身。

2026-10-08 00:04 回放：「数据分析师」（河北日上防盗门）连着两天被否决词「销售」杀掉，
10-07+10-08 在目标标题里这种形状有 15 条。它的 JD 五处"销售"全在讲数据——
"提取、清洗销售及进销存数据""多维度分析防盗门销售数据""监控销售指标波动"。
反过来「AI+数据合伙人」写"有一定的销售/商务拓展经验"，那是在要销售能力，照旧得拦。
"""
import sys
from pathlib import Path

ROOT = Path(__file__).resolve().parent.parent
sys.path.insert(0, str(ROOT))

from boss_bot.intent import body_veto_hit  # noqa: E402

# 取自 data/greet_records.json 里这两条真实记录（只抹平了换行）
数据分析师_JD = (
    "工作周期：长期兼职 结算⽅式：⽉结 招聘截止时间：2026-11-23 岗位职责 "
    "1. 从 ERP 系统提取、清洗销售及进销存数据，维护统一统计口径； "
    "2. 多维度分析防盗门销售数据：区域、渠道、产品款式、价格、订单特征，搭建可视化看板； "
    "3. 挖掘客户受众画像，分析客户偏好； "
    "4. 识别爆款 / 滞销产品，输出分析报告，为采购选品、定价、库存备货提供数据支撑； "
    "5. 监控销售指标波动，定位业务异常，对接销售、采购部门落地数据建议。 "
    "任职要求 1. 大专及以上学历，能独立导出 ERP 业务数据； "
    "3. 具备业务分析思维，对数字敏感，可独立完成客户画像、销售专项分析并输出报告。"
)

数据合伙人_JD = (
    "工作周期：长期兼职 我们在找什么样的人？ 认可\"AI+数据咨询\"这个方向，有兴趣长期一起做 "
    "有一定的销售/商务拓展经验，或者性格外向、擅长陌生开发 "
    "你会做什么？ 通过陌拜、线上渠道(小红书/BOSS)、展会、人脉等方式寻找连锁品牌客户线索。"
)

否决词 = ["销售", "中介", "需坐班"]


class 数据岗标题下的销售Test:
    def test_销售当数据域时放行(self):
        """这份工分析的是销售数据，不是去做销售。"""
        assert body_veto_hit(否决词, [], title="数据分析师",
                             text=数据分析师_JD) == ""

    def test_要销售经验的照旧拦(self):
        assert body_veto_hit(否决词, [], title="AI+数据合伙人",
                             text=数据合伙人_JD) == "销售"

    def test_标题不是数据岗时正文销售照样定罪(self):
        """白名单只给数据/分析/标注这三个方向，别的标题维持原口径。"""
        jd = "岗位职责 1. 负责公司产品的销售推广； 2. 整理销售数据周报。"
        assert body_veto_hit(否决词, [], title="线上运营专员",
                             text=jd) == "销售"

    def test_数据岗标题但明写做销售也拦(self):
        jd = "岗位职责 1. 负责区域销售任务的达成； 2. 用数据复盘销售情况。"
        assert body_veto_hit(否决词, [], title="数据分析专员",
                             text=jd) == "销售"

    def test_别的否决词不受这条影响(self):
        """需坐班这类条件词还是走否定式那一套，不在这次豁免里。"""
        jd = "岗位职责 1. 需坐班，配合团队完成销售数据整理。"
        assert body_veto_hit(否决词, [], title="数据分析师",
                             text=jd) == "需坐班"

    def test_标题带销售仍然拦(self):
        """豁免只作用于正文那一遍；他自己填的否决词写在标题上照样算数。"""
        assert body_veto_hit(否决词, [], title="销售数据分析师",
                             text=数据分析师_JD) == "销售"
